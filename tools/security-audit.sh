#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
fail(){ echo "SECURITY AUDIT: FAIL: $*" >&2; exit 1; }
pass(){ echo "SECURITY AUDIT: PASS: $*"; }
MANIFEST="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/RuntimeManifest.kt"
EMBED="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/EmbeddedLinuxRuntime.kt"
BACKEND="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/RuntimeBackend.kt"
NATIVE="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/NativeRuntime.kt"
WALLET_ARGS="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/WalletToolArgs.kt"
INSTALL="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/RuntimeInstaller.kt"
RPC="$ROOT/app/src/main/java/org/stohncoin/wallet/wallet/WalletRpc.kt"
NODE="$ROOT/app/src/main/java/org/stohncoin/wallet/core/NodeController.kt"
UI="$ROOT/app/src/main/java/org/stohncoin/wallet/ui/StohnWalletScreen.kt"
UIDIR="$ROOT/app/src/main/java/org/stohncoin/wallet/ui"
AM="$ROOT/app/src/main/AndroidManifest.xml"
BUILD="$ROOT/app/build.gradle.kts"
AUTH="$ROOT/app/src/main/java/org/stohncoin/wallet/security/AppAuthManager.kt"
PIN="$ROOT/app/src/main/java/org/stohncoin/wallet/security/PinHasher.kt"
THROTTLE="$ROOT/app/src/main/java/org/stohncoin/wallet/security/PinThrottle.kt"
MAIN="$ROOT/app/src/main/java/org/stohncoin/wallet/MainActivity.kt"
SERVICE="$ROOT/app/src/main/java/org/stohncoin/wallet/core/NodeService.kt"
[[ -f "$MANIFEST" && -f "$EMBED" && -f "$INSTALL" && -f "$RPC" && -f "$NODE" && -f "$UI" ]] || fail "required source file missing"
[[ -f "$AUTH" && -f "$PIN" && -f "$THROTTLE" && -f "$MAIN" && -f "$SERVICE" ]] || fail "app-lock source file missing"
! grep -R "v1.10.1\|termux/proot-distro/releases/download/v1.10.1" "$ROOT/app" "$ROOT/scripts" "$ROOT/.github" >/dev/null 2>&1 || fail "obsolete Debian source remains"
! grep -F 'android:usesCleartextTraffic="true"' "$AM" >/dev/null || fail "global cleartext traffic enabled"
grep -F 'android.permission.ACCESS_NETWORK_STATE' "$AM" >/dev/null || fail "network-state permission missing"
grep -F 'android:allowBackup="false"' "$AM" >/dev/null || fail "Android backup is enabled"
grep -F 'android:exported="false"' "$AM" >/dev/null || fail "foreground service exported"
! grep -E 'LD_LIBRARY_PATH.*nativeDir|nativeDir.*LD_LIBRARY_PATH' "$EMBED" >/dev/null || fail "Android native library directory leaked into glibc runtime"
grep -F 'PROOT_LOADER' "$EMBED" >/dev/null || fail "PRoot loader not configured"
grep -F 'RuntimeTemp.prepare' "$EMBED" >/dev/null || fail "PRoot temp directory is not scoped to its own cache folder"
grep -F 'RuntimeTemp.purge' "$EMBED" >/dev/null || fail "PRoot temp directory is never cleaned up"
grep -F 'is NativeLaunch.Ready' "$BACKEND" >/dev/null || fail "backend factory does not gate the native runtime on a verified binary"
grep -F 'NativeLaunch.requireReady' "$NATIVE" >/dev/null || fail "native backend does not re-verify its pins before exec"
grep -F 'KeyExportGuard.requireWalletToolCommand' "$WALLET_ARGS" >/dev/null || fail "key export guard is not in the shared wallet tool argument builder"
grep -F 'rpcallowip=127.0.0.1' "$BACKEND" >/dev/null || fail "RPC allowlist is not loopback-only"
grep -F 'rpcbind=127.0.0.1' "$BACKEND" >/dev/null || fail "RPC bind is not loopback-only"
grep -F 'https://' "$INSTALL" >/dev/null || fail "runtime installer lacks HTTPS enforcement"
grep -F 'Integrity check failed' "$INSTALL" >/dev/null || fail "runtime integrity verification missing"
grep -F 'safeArchivePath' "$INSTALL" >/dev/null || fail "archive path validation missing"
grep -F 'safeLinkTarget' "$INSTALL" >/dev/null || fail "symlink containment validation missing"
grep -F 'MAX_EXTRACTED_BYTES' "$INSTALL" >/dev/null || fail "extraction size limit missing"
grep -F 'MAX_ARCHIVE_ENTRIES' "$INSTALL" >/dev/null || fail "archive entry limit missing"
grep -F 'walletpassphrasechange' "$RPC" >/dev/null || fail "wallet passphrase change RPC missing"
grep -F 'encryptwallet' "$RPC" >/dev/null || fail "wallet encryption RPC missing"
grep -F 'passphrase.fill' "$RPC" >/dev/null || fail "RPC passphrase wipe missing"
grep -R -F 'passphrase = ""' "$UIDIR" >/dev/null || fail "UI passphrase clearing missing"
grep -F 'walletMutex' "$NODE" >/dev/null || fail "wallet operation serialization missing"
grep -F 'keepDebugSymbols += "**/*.so"' "$BUILD" >/dev/null || fail "native packaging hardening missing"
if grep -R -nE 'TODO|FIXME|XXX' "$ROOT/app/src/main/java" >/tmp/stohn_todos.txt 2>/dev/null; then
  echo "SECURITY AUDIT: NOTICE: TODO/FIXME markers remain:"
  head -20 /tmp/stohn_todos.txt
fi
grep -F 'PBKDF2WithHmacSHA256' "$PIN" >/dev/null || fail "app-lock PIN is not PBKDF2-HMAC-SHA256"
grep -F 'SecureRandom' "$PIN" >/dev/null || fail "app-lock PIN salt is not randomly generated"
grep -F 'MessageDigest.isEqual' "$PIN" >/dev/null || fail "app-lock PIN comparison is not constant time"
grep -F 'PinThrottle.afterFailure' "$AUTH" >/dev/null || fail "app-lock PIN throttling is not persisted"
grep -F 'PinThrottle.isBlocked' "$AUTH" >/dev/null || fail "app-lock PIN throttling is not enforced"
grep -F 'if (enabled && !hasPin(store))' "$AUTH" >/dev/null || fail "biometric unlock can be enabled without a PIN"
# The guard lives in the store-based core, so the Context entry point must delegate to it rather
# than developing a second, unchecked path.
grep -F 'setBiometricEnabled(prefs(context), enabled)' "$AUTH" >/dev/null \
  || fail "context entry point bypasses the biometric PIN guard"
grep -F 'FLAG_SECURE' "$MAIN" >/dev/null || fail "FLAG_SECURE missing: wallet content would appear in recents"
grep -F 'VISIBILITY_SECRET' "$SERVICE" >/dev/null || fail "node notification is not redacted on the lock screen"
[[ ! -f "$ROOT/app/src/main/java/org/stohncoin/wallet/security/WalletKeystore.kt" ]] || fail "unused WalletKeystore class reappeared"
[[ ! -f "$ROOT/app/src/main/java/org/stohncoin/wallet/wallet/WalletManager.kt" ]] || fail "unused WalletManager class reappeared"
grep -F 'android:authorities="${applicationId}.fileprovider"' "$AM" >/dev/null || fail "FileProvider authority missing"
grep -F 'android:exported="false"' "$AM" >/dev/null || fail "manifest has an exported component"
[[ -f "$ROOT/app/src/main/res/xml/file_paths.xml" ]] || fail "FileProvider paths file missing"
grep -F 'path="qr-share/"' "$ROOT/app/src/main/res/xml/file_paths.xml" >/dev/null || fail "QR share path is not confined to its cache directory"
UPDATER="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/SignedRuntimeManifest.kt"
[[ -f "$UPDATER" ]] || fail "runtime manifest updater missing"
grep -F 'SignedRuntimeManifest.effective' "$BACKEND" >/dev/null || fail "backend factory does not resolve pins through the signed update path"
grep -F 'SignedRuntimeManifest.effective' "$INSTALL" >/dev/null || fail "runtime installer does not use the staged pins"
grep -F 'Signature.getInstance' "$UPDATER" >/dev/null || fail "runtime manifest is not signature-checked"
grep -F 'is not newer than the built-in' "$UPDATER" >/dev/null || fail "runtime manifest downgrade is not refused"
grep -F 'Runtime manifest release key is not configured' "$UPDATER" >/dev/null || fail "unconfigured release key must refuse documents"
TRANSPORT="$ROOT/app/src/main/java/org/stohncoin/wallet/runtime/RuntimeManifestTransport.kt"
[[ -f "$TRANSPORT" ]] || fail "runtime manifest transport missing"
grep -F 'RuntimeManifest.MANIFEST_URL' "$TRANSPORT" >/dev/null || fail "manifest transport does not take its endpoint from RuntimeManifest"
grep -F 'instanceFollowRedirects = false' "$TRANSPORT" >/dev/null || fail "manifest transport lets the platform follow redirects unchecked"
grep -F 'redirect left HTTPS' "$TRANSPORT" >/dev/null || fail "manifest transport accepts a redirect off HTTPS"
grep -F 'MAX_REDIRECTS' "$TRANSPORT" >/dev/null || fail "manifest redirect limit missing"
grep -F 'SignedRuntimeManifest.verifyDocument' "$TRANSPORT" >/dev/null || fail "manifest transport does not verify before staging"
grep -F 'SignedRuntimeManifest.stage' "$TRANSPORT" >/dev/null || fail "manifest transport bypasses the verified staging path"
! grep -F 'UPDATE_FILE' "$TRANSPORT" >/dev/null || fail "manifest transport writes the staged manifest itself"
grep -F 'RuntimeManifestTransport.refresh' "$MAIN" >/dev/null || fail "app never attempts a runtime manifest update"
pass "security and containment checks"
